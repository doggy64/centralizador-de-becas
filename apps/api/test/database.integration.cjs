const {randomUUID}=require("node:crypto");
const path=require("node:path");
const request=require("supertest");
const Parser=require("@apidevtools/swagger-parser");
const Ajv=require("ajv");
const addFormats=require("ajv-formats");
const {PrismaClient}=require("@prisma/client");
const {createApp}=require("../dist/app");
const {importCandidate,review,verifyChannel}=require("../../worker/dist/editorial");
const url=process.env.TEST_DATABASE_URL;
if(!url||!new URL(url).pathname.endsWith("_test"))throw Error("Se requiere TEST_DATABASE_URL con base dedicada *_test");
process.env.DATABASE_URL=url;
const db=new PrismaClient();
const slug="test-"+randomUUID();
const sourceUrl="https://www.oas.org/test-offline";
const target="https://www.oas.org/apply-test";
const evidence={sourceUrl,excerpt:"Fuente de prueba "+target,pageNumber:null};
const c={institution:{key:slug,name:"Institución QA",websiteUrl:null},program:{key:"qa",name:"Programa QA"},slug,editionKey:"2027",title:"Ingeniería "+slug,summary:"Caso sintético de integración",sourceUrl,evidence,levels:["MASTER"],areas:["ingenieria"],countries:["BO"],channels:[{type:"FORM_URL",purpose:"APPLY",target,evidence},{type:"EMAIL",purpose:"CONTACT",target:"info@example.org",evidence}],requirements:[{label:"Documento",required:null,evidence}],benefits:[]};
let app,api,spec;
function conforms(route,body){
 const ajv=addFormats(new Ajv({strict:false,allErrors:true}));
 const valid=ajv.compile(spec.paths[route].get.responses["200"].content["application/json"].schema);
 if(!valid(body))throw Error(ajv.errorsText(valid.errors));
}
beforeAll(async()=>{spec=await Parser.validate(path.resolve(__dirname,"../../../contracts/openapi.yaml"));app=await createApp();await app.init();api=request(app.getHttpServer());});
afterAll(async()=>{await app?.close();await db.$disconnect();});
test("dry-run, idempotencia, procedencia múltiple, edición, revisión y consumo v1",async()=>{
 await importCandidate(db,c,"test",true);
 expect(await db.scholarship.count({where:{slug}})).toBe(0);
 const [a,b]=await Promise.all([importCandidate(db,c,"test"),importCandidate(db,c,"test")]);
 expect(a.id).toBe(b.id);
 const other="https://www.chevening.org/test-offline";
 await importCandidate(db,{...c,sourceUrl:other,evidence:{...evidence,sourceUrl:other}},"test");
 expect(await db.evidence.count({where:{callId:a.id,field:"summary"}})).toBe(2);
 await importCandidate(db,{...c,editionKey:"2028",slug:slug+"-next"},"test");
 await api.get("/api/v1/scholarships/"+slug).expect(404);
 await expect(review(db,slug,"publish","test","fuente contrastada")).rejects.toThrow();
 await review(db,slug,"submit","test","lista para revisión");
 const channel=await db.channel.findFirstOrThrow({where:{callId:a.id,purpose:"APPLY"}});
 await verifyChannel(db,channel.id,"editor","Designación exacta comprobada","VERIFIED");
 await review(db,slug,"publish","editor","Fuente oficial y datos corroborados");
 const route="/api/v1/scholarships";
 const res=await api.get(route).query({q:"ingenieria "+slug,level:"MASTER",country:"BO",area:"ingenieria",status:"TO_CONFIRM",limit:1}).expect(200);
 conforms(route,res.body);
 expect(res.body.meta).toEqual({page:1,limit:1,total:1,totalPages:1,hasNextPage:false});
 expect(res.body.data[0].slug).toBe(slug);
 const page2=await api.get(route).query({q:slug,page:2,limit:1}).expect(200);
 expect(page2.body.data).toEqual([]);
 const detail=await api.get(route+"/"+slug).expect(200);
 conforms(route+"/{slug}",detail.body);
 expect(detail.body.applicationChannels.find(c=>c.purpose==="APPLY").urlOrEmail).toBe(target);
 expect(detail.body.applicationChannels.find(c=>c.purpose==="CONTACT").urlOrEmail).toBeNull();
 const catalog=await api.get("/api/v1/catalogs/filters").expect(200);
 conforms("/api/v1/catalogs/filters",catalog.body);
 for(const q of [{page:0},{limit:49},{level:"BAD"},{status:"BAD"},{area:["ingenieria","ciencias"]}])await api.get(route).query(q).expect(400);
 await importCandidate(db,{...c,summary:"Cambio sustantivo"},"editor");
 await api.get(route+"/"+slug).expect(404);
 expect(await db.reviewEvent.count({where:{callId:a.id}})).toBeGreaterThanOrEqual(5);
},30000);
